// Renders the logo (public/logo.svg) and the Lucide icons used in emails to PNG, and writes them
// as base64 to server/features/mail/assets/emailAssets.ts. Email clients such as Gmail and Outlook
// don't show SVG, and embedding the PNGs means emails need no hosted images.
//
// Run after changing the logo or the icon list: npm run email:assets

import { writeFileSync } from "node:fs";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as lucide from "lucide-react";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const output = path.join(root, "server/features/mail/assets/emailAssets.ts");

// Colors from app/globals.css: muted ink for field icons, red on ink tiles, paper on red buttons.
const colors = { muted: "#8a8780", accent: "#c83232", paper: "#f7f6f0" };

/** Rendered at 3x the size shown in emails, so they stay sharp on high-density screens. */
const SCALE = 3;

// [asset name, Lucide icon, color, display size in px]
const icons = [
  ["tile-check", "CircleCheck", colors.accent, 20],
  ["tile-inbox", "Inbox", colors.accent, 20],
  ["tile-ticket", "Ticket", colors.accent, 16],
  ["row-topic", "MessageSquare", colors.muted, 14],
  ["row-user", "User", colors.muted, 14],
  ["row-mail", "Mail", colors.muted, 14],
  ["row-phone", "Phone", colors.muted, 14],
  ["row-order", "Hash", colors.muted, 14],
  ["row-time", "Clock", colors.muted, 14],
  ["button-reply", "Reply", colors.paper, 14],
  ["button-arrow", "ArrowRight", colors.paper, 14],
];

const toPng = (svg, size) =>
  sharp(Buffer.from(svg), { density: 72 * SCALE * 4 })
    .resize(size * SCALE, size * SCALE)
    .png({ compressionLevel: 9, palette: true })
    .toBuffer();

const assets = {};

const logo = await readFile(path.join(root, "public/logo.svg"), "utf8");
assets.logo = { size: 36, png: await toPng(logo, 36) };

for (const [name, icon, color, size] of icons) {
  const Icon = lucide[icon];
  if (!Icon) throw new Error(`lucide-react has no icon called ${icon}`);
  const svg = renderToStaticMarkup(createElement(Icon, { size: 24, color, strokeWidth: 1.75 }));
  assets[name] = { size, png: await toPng(svg, size) };
}

const entries = Object.entries(assets)
  .map(([name, { size, png }]) => `  "${name}": { size: ${size}, png: "${png.toString("base64")}" },`)
  .join("\n");

writeFileSync(
  output,
  `// Generated by scripts/build-email-assets.mjs (npm run email:assets). Don't edit by hand.
// PNG images embedded in emails: \`size\` is the display size in px; the image is ${SCALE}x that.

export const emailAssets = {
${entries}
} as const;

export type EmailAsset = keyof typeof emailAssets;
`,
);

const bytes = Object.values(assets).reduce((total, { png }) => total + png.length, 0);
console.log(`Wrote ${Object.keys(assets).length} images (${(bytes / 1024).toFixed(1)} KB) to ${path.relative(root, output)}`);
